#!/usr/bin/env node
// Discovers every @convex-dev/* package on npm, filters down to actual Convex
// Components (those exporting `./convex.config.js`), and snapshots each one's
// README into chef-agent/prompts/components/snapshots/. Run with
// `pnpm run sync:components`.
//
// Writes per-component README files plus a `_index.json` manifest consumed by
// chef-agent/prompts/components/registry.ts.

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');
const SNAPSHOTS_DIR = join(REPO_ROOT, 'chef-agent', 'prompts', 'components', 'snapshots');
const NPM_SEARCH = 'https://registry.npmjs.org/-/v1/search?text=convex-dev&size=250';

async function readSnapshot(filename) {
  return readFile(join(SNAPSHOTS_DIR, filename), 'utf8');
}

async function fetchJson(url) {
  const res = await fetch(url, { headers: { accept: 'application/json' } });
  if (!res.ok) throw new Error(`${url} → HTTP ${res.status}`);
  return res.json();
}

function isComponentExports(exportsField) {
  if (!exportsField || typeof exportsField !== 'object' || Array.isArray(exportsField)) {
    return false;
  }
  return (
    './convex.config.js' in exportsField ||
    './convex.config' in exportsField ||
    './convex.config.ts' in exportsField
  );
}

function parseGithubRepo(meta) {
  const candidates = [
    typeof meta.homepage === 'string' ? meta.homepage : '',
    meta.repository?.url ?? '',
    typeof meta.repository === 'string' ? meta.repository : '',
  ];
  for (const candidate of candidates) {
    const match = /github\.com[/:]([\w.-]+)\/([\w.-]+?)(?:\.git|#.*)?(?:\/|$)/.exec(candidate);
    if (match) return `${match[1]}/${match[2]}`;
  }
  return null;
}

async function fetchGithubReadme(repo) {
  for (const branch of ['main', 'master']) {
    const url = `https://raw.githubusercontent.com/${repo}/${branch}/README.md`;
    try {
      const r = await fetch(url);
      if (r.ok) {
        const text = (await r.text()).trim();
        if (text) return text;
      }
    } catch {
      // continue
    }
  }
  return '';
}

async function main() {
  console.log('Discovering @convex-dev/* packages via npm search…');
  const search = await fetchJson(NPM_SEARCH);
  const names = search.objects
    .map((o) => o.package.name)
    .filter((n) => n.startsWith('@convex-dev/'))
    .sort();
  console.log(`Found ${names.length} packages in the @convex-dev scope.\n`);

  await mkdir(SNAPSHOTS_DIR, { recursive: true });

  const components = [];
  const skipped = [];

  for (const npmName of names) {
    const slug = npmName.slice('@convex-dev/'.length);
    let meta;
    try {
      meta = await fetchJson(`https://registry.npmjs.org/${encodeURIComponent(npmName)}`);
    } catch (e) {
      skipped.push({ name: npmName, reason: `fetch: ${e.message}` });
      continue;
    }

    const latestTag = meta['dist-tags']?.latest;
    const latestVersion = latestTag ? meta.versions?.[latestTag] : undefined;
    if (!latestVersion) {
      skipped.push({ name: npmName, reason: 'no latest version metadata' });
      continue;
    }

    if (!isComponentExports(latestVersion.exports)) {
      skipped.push({ name: npmName, reason: 'not a component (no ./convex.config.js export)' });
      continue;
    }

    let readme = typeof meta.readme === 'string' ? meta.readme.trim() : '';
    let readmeSource = 'npm';
    if (!readme) {
      const repo = parseGithubRepo(meta);
      if (repo) {
        readme = await fetchGithubReadme(repo);
        readmeSource = `github:${repo}`;
      }
    }
    if (!readme) {
      skipped.push({ name: npmName, reason: 'no README on npm or GitHub' });
      continue;
    }

    const file = `${slug}.md`;
    await writeFile(join(SNAPSHOTS_DIR, file), readme + '\n', 'utf8');

    components.push({
      slug,
      npmPackage: npmName,
      description: (meta.description ?? '').trim(),
      version: latestTag,
      homepage: meta.homepage ?? null,
      readmeFile: file,
    });
    console.log(`  + ${npmName}@${latestTag} → snapshots/${file}  (readme: ${readmeSource})`);
  }

  components.sort((a, b) => a.slug.localeCompare(b.slug));
  const generatedAt = new Date().toISOString();
  await writeFile(
    join(SNAPSHOTS_DIR, '_index.json'),
    JSON.stringify({ generatedAt, components }, null, 2) + '\n',
    'utf8',
  );

  // Also emit a TypeScript module that inlines every README. registry.ts
  // imports from this so the content is available in both Node (test-kitchen)
  // and browser (Remix app) without needing a bundler-specific glob.
  const lines = [
    '// AUTO-GENERATED by scripts/fetch-component-readmes.mjs. Do not edit.',
    `// Last sync: ${generatedAt}`,
    '',
    'export const snapshotReadmes: Record<string, string> = {',
  ];
  for (const c of components) {
    const safe = c.readmeFile.replace(/\.md$/, '');
    const raw = await readSnapshot(c.readmeFile);
    // Use a string literal with `${'`'}` style escaping so backticks and ${} in
    // markdown don't blow up the template literal.
    const escaped = raw.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
    lines.push(`  ${JSON.stringify(safe)}: \`${escaped}\`,`);
  }
  lines.push('};', '');
  await writeFile(join(SNAPSHOTS_DIR, 'snapshots.generated.ts'), lines.join('\n'), 'utf8');

  console.log(`\nWrote ${components.length} component snapshots + _index.json + snapshots.generated.ts.`);
  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} packages (non-components or missing data):`);
    for (const s of skipped) console.log(`  - ${s.name} (${s.reason})`);
  }
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
